package rypt

import (
	"context"
	"errors"
	"net/http"
)

// dataKeyLen is the length of a data key the service generates.
const dataKeyLen = 32

// Encrypt encrypts plaintext under a key's primary version and returns the
// ciphertext. The ciphertext names the version it was made under, so
// [Client.Decrypt] keeps working after a rotation while that version is
// kept.
//
// plaintext is 1 to 65,536 bytes; on the hsm tier, plaintext and aad
// together are at most 8,176 bytes. aad, the additional authenticated data,
// may be nil; when it is not, the same aad must be given to Decrypt and
// Rewrap. aad is at most 65,520 bytes on the software and hsm tiers and
// 65,536 on the others.
//
// The call needs an API token with the encrypt action, and is one metered
// operation. Where billing is configured, a paid key whose tenant's billing
// has lapsed fails with [CodeBillingRequired]. Encrypt is retried after a
// transient failure, and each attempt that reaches the key may be counted.
func (c *Client) Encrypt(ctx context.Context, keyID string, plaintext, aad []byte) ([]byte, error) {
	if len(plaintext) == 0 {
		return nil, errors.New("rypt: the plaintext is empty")
	}
	var res ciphertextResponse
	err := c.binaryCall(ctx, keyID, "/encrypt", &res,
		binaryField{name: "plaintext", value: plaintext},
		binaryField{name: "aad", value: aad, optional: true})
	if err != nil {
		return nil, err
	}
	return res.Ciphertext, nil
}

// Decrypt decrypts a ciphertext made by [Client.Encrypt] or
// [Client.Rewrap] under any version the key still has, and returns the
// plaintext. aad must be what the ciphertext was made with, or nil if none
// was. The caller should clear the plaintext when done with it.
//
// A ciphertext the key did not make, a wrong aad, or a ciphertext under a
// version that has been destroyed fails with [CodeInvalidCiphertext].
//
// The call needs an API token with the decrypt action, and is one metered
// operation. It is never refused for billing. Decrypt is retried after a
// transient failure, and each attempt that reaches the key may be counted.
func (c *Client) Decrypt(ctx context.Context, keyID string, ciphertext, aad []byte) ([]byte, error) {
	if len(ciphertext) == 0 {
		return nil, errors.New("rypt: the ciphertext is empty")
	}
	var res plaintextResponse
	err := c.binaryCall(ctx, keyID, "/decrypt", &res,
		binaryField{name: "ciphertext", value: ciphertext},
		binaryField{name: "aad", value: aad, optional: true})
	if err != nil {
		return nil, err
	}
	return res.Plaintext, nil
}

// Rewrap decrypts a ciphertext made by [Client.Encrypt] or Rewrap under
// whatever version it names, and encrypts the plaintext again under the
// key's primary version, without the plaintext leaving the service. aad
// must be what the ciphertext was made with, or nil; it is applied to the
// new ciphertext too. Use it after [Client.RotateKey] to move ciphertext off
// a retiring version.
//
// The call needs an API token with the rewrap action, and is one metered
// operation. Where billing is configured, a paid key whose tenant's billing
// has lapsed fails with [CodeBillingRequired]. Rewrap is retried after a
// transient failure, and each attempt that reaches the key may be counted.
func (c *Client) Rewrap(ctx context.Context, keyID string, ciphertext, aad []byte) ([]byte, error) {
	if len(ciphertext) == 0 {
		return nil, errors.New("rypt: the ciphertext is empty")
	}
	var res ciphertextResponse
	err := c.binaryCall(ctx, keyID, "/rewrap", &res,
		binaryField{name: "ciphertext", value: ciphertext},
		binaryField{name: "aad", value: aad, optional: true})
	if err != nil {
		return nil, err
	}
	return res.Ciphertext, nil
}

// DataKey is a data key generated by [Client.GenerateDataKey].
type DataKey struct {
	// Plaintext is the 32-byte data key, to encrypt data with locally. The
	// caller should clear it when done with it and never store it.
	Plaintext []byte
	// Wrapped is the data key encrypted under the rypt key. Store it next
	// to the data, and recover the data key from it with [Client.Unwrap].
	Wrapped []byte
}

// GenerateDataKey asks the service to generate a random 32-byte data key,
// and returns it together with its wrapped form. This is the usual first
// step of envelope encryption: encrypt the data locally with
// [DataKey.Plaintext], for example with AES-256-GCM, store [DataKey.Wrapped]
// with it, and clear the data key.
//
// aad may be nil. When it is not, it binds the wrapped key to its context,
// such as the id of the record it protects, and the same aad must be given
// to [Client.Unwrap].
//
// The call needs an API token with the wrap action, and is one metered
// operation. Where billing is configured, a paid key whose tenant's billing
// has lapsed fails with [CodeBillingRequired]. GenerateDataKey is retried
// after a transient failure, and each attempt that reaches the key may be
// counted.
func (c *Client) GenerateDataKey(ctx context.Context, keyID string, aad []byte) (*DataKey, error) {
	res := wrapResponse{generated: true}
	err := c.binaryCall(ctx, keyID, "/wrap", &res, binaryField{name: "aad", value: aad, optional: true})
	if err != nil {
		return nil, err
	}
	return &DataKey{Plaintext: res.DEK, Wrapped: res.Wrapped}, nil
}

// Wrap encrypts a data key the caller made under a rypt key, and returns
// the wrapped form. dek must be 16, 24 or 32 bytes. To have the service
// generate the data key instead, use [Client.GenerateDataKey].
//
// aad may be nil. When it is not, it binds the wrapped key to its context,
// and the same aad must be given to [Client.Unwrap].
//
// The call needs an API token with the wrap action, and is one metered
// operation. Where billing is configured, a paid key whose tenant's billing
// has lapsed fails with [CodeBillingRequired]. Wrap is retried after a
// transient failure, and each attempt that reaches the key may be counted.
func (c *Client) Wrap(ctx context.Context, keyID string, dek, aad []byte) ([]byte, error) {
	// An empty dek would be left out of the request, and the service would
	// generate one the caller never sees.
	if len(dek) == 0 {
		return nil, errors.New("rypt: the data key to wrap is empty; use GenerateDataKey to have one generated")
	}
	var res wrapResponse
	err := c.binaryCall(ctx, keyID, "/wrap", &res,
		binaryField{name: "dek", value: dek},
		binaryField{name: "aad", value: aad, optional: true})
	// The service does not send back a data key it was given.
	clear(res.DEK)
	if err != nil {
		return nil, err
	}
	return res.Wrapped, nil
}

// Unwrap recovers a data key from the wrapped form that
// [Client.GenerateDataKey] or [Client.Wrap] returned. aad must be what the
// key was wrapped with, or nil if none was; a different one fails with
// [CodeInvalidCiphertext]. The caller should clear the data key when done
// with it.
//
// The call needs an API token with the unwrap action, and is one metered
// operation. It is never refused for billing. Unwrap is retried after a
// transient failure, and each attempt that reaches the key may be counted.
func (c *Client) Unwrap(ctx context.Context, keyID string, wrapped, aad []byte) ([]byte, error) {
	if len(wrapped) == 0 {
		return nil, errors.New("rypt: the wrapped data key is empty")
	}
	var res unwrapResponse
	err := c.binaryCall(ctx, keyID, "/unwrap", &res,
		binaryField{name: "wrapped", value: wrapped},
		binaryField{name: "aad", value: aad, optional: true})
	if err != nil {
		return nil, err
	}
	return res.DEK, nil
}

// binaryCall posts a body of base64 fields to /v1/keys/{keyID}{suffix} and
// decodes the answer into out. It clears the request body when done, since
// it may hold a plaintext or data key. These calls are all safe to repeat.
func (c *Client) binaryCall(ctx context.Context, keyID, suffix string, out any, fields ...binaryField) error {
	path, err := idPath("keys", "key ID", keyID, suffix)
	if err != nil {
		return err
	}
	body := binaryBody(fields...)
	defer clear(body)
	return c.do(ctx, &request{method: http.MethodPost, path: path, body: body, retry: retryIfTransient}, out)
}

// ciphertextResponse is the body of encrypt and rewrap.
type ciphertextResponse struct {
	Ciphertext []byte `json:"ciphertext"`
}

func (r *ciphertextResponse) problem() string {
	if len(r.Ciphertext) == 0 {
		return "ciphertext is missing or empty"
	}
	return ""
}

// plaintextResponse is the body of decrypt.
type plaintextResponse struct {
	Plaintext []byte `json:"plaintext"`
}

func (r *plaintextResponse) problem() string {
	if len(r.Plaintext) == 0 {
		// encrypt refuses an empty plaintext, so none decrypts to one.
		return "plaintext is missing or empty"
	}
	return ""
}

func (r *plaintextResponse) clearSecrets() { clear(r.Plaintext) }

// wrapResponse is the body of wrap. generated says whether the request
// asked the service to generate the data key, in which case the body
// carries it.
type wrapResponse struct {
	DEK       []byte `json:"dek"`
	Wrapped   []byte `json:"wrapped"`
	generated bool
}

func (r *wrapResponse) problem() string {
	switch {
	case r.generated && r.DEK == nil:
		return "dek is missing"
	case r.generated && len(r.DEK) != dataKeyLen:
		return "dek is not 32 bytes"
	case len(r.Wrapped) == 0:
		return "wrapped is missing or empty"
	}
	return ""
}

func (r *wrapResponse) clearSecrets() { clear(r.DEK) }

// unwrapResponse is the body of unwrap.
type unwrapResponse struct {
	DEK []byte `json:"dek"`
}

func (r *unwrapResponse) problem() string {
	if len(r.DEK) == 0 {
		return "dek is missing or empty"
	}
	return ""
}

func (r *unwrapResponse) clearSecrets() { clear(r.DEK) }
